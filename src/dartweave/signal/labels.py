"""무엇을 '부실' 로 셀 것인가 — 한 곳에 모아둔다.

왜 함수로 가두나:
  스크립트마다 `"해산" not in event_type` 을 손으로 쓰고 있었다. 라벨 출처가
  하나였을 때는 버텼지만, 상장폐지가 들어오면서 **비부실 유형이 여덟 가지**로 늘었다.
  합병·스팩청산·이전상장·완전자회사화를 부실로 세면 "합병당한 회사" 를 부실로
  예측하는 셈이 되어 라벨이 통째로 오염된다.

  한 군데만 고치면 모든 검정이 같이 바뀌도록 여기 가둔다. `db/asof.py` 가 시점
  조회를 가둔 것과 같은 이유다.

명시 목록을 쓰는 이유:
  "부실아님" 같은 표식을 문자열로 찾으면, 새 유형을 추가할 때 표식을 빠뜨린 쪽이
  조용히 부실로 들어간다. **모르는 유형은 부실이 아니다** 로 두는 편이 안전하다 —
  없는 신호를 만드는 것보다 있는 신호를 놓치는 쪽이 낫다.
"""
from __future__ import annotations

# DART 주요사항보고
DART_DISTRESS = frozenset({"부도", "회생", "관리절차", "파산"})

# ⚠️ **영업정지를 뺐다.** 사용자가 답안지를 직접 열어보다 잡혔다.
#
#   신한은행 557조 · 하나은행 532조(21건) · 우리은행 486조 · LG전자 · KT&G
#
# 금융회사의 "영업정지" 는 금융당국이 특정 업무를 일부 정지시킨 **제재**지 회사가
# 망한 게 아니다. 284건 · 173곳 중 27곳이 자산 1조 이상이었다. 사유가 detail 에
# 안 들어 있어서 큰 것과 진짜를 가릴 방법도 없다.
#
# 빼면 라벨이 526건 남는다. 그리고 빼니까 **신호가 전부 강해졌다** — 오염이
# 신호를 부풀린 게 아니라 깎고 있었다는 뜻이다 (T=2024 기준):
#
#   전체 부실률          3.94% → 2.36%
#   결손금               x2.36 → x3.15
#   영업현금흐름 음수      x2.06 → x2.55
#   신호 없이 부실난 곳    13건(14%) → 0건(0%)
#
# 다른 라벨에도 같은 검사를 했다. 회생의 대기업 3곳(KG모빌리티·콘텐트리중앙·
# 제이알글로벌리츠)과 부도·관리절차의 태영건설은 실제로 회생·워크아웃을 갔으므로
# 정당한 라벨이다. 영업정지만 오염이었다.
#
# 사유를 읽어 가릴 수 있게 되면 되살릴 수 있다 — 그때는 원문을 받아야 한다.
EXCLUDED_AMBIGUOUS = frozenset({"영업정지"})

# KRX 상장폐지 — 사유가 기업 부실인 것만. 합병·스팩청산·이전상장·자진폐지는 뺀다.
DELISTING_DISTRESS = frozenset({
    "상장폐지(감사의견)",
    "상장폐지(실질심사)",
    "상장폐지(파산)",
    "상장폐지(보고서 미제출)",
    # 최종부도로 인한 폐지. 분류 규칙이 없어 "기타" 로 떨어져 있던 걸 되찾았다 —
    # 사유 문구가 "발행한 어음 또는 수표가 ... 최종부도로 결정" 이다.
    "상장폐지(부도)",
})

DISTRESS_TYPES = DART_DISTRESS | DELISTING_DISTRESS


def is_distress(event_type: str) -> bool:
    """이 사건을 부실 라벨로 셀 것인가. 목록에 없으면 세지 않는다."""
    return event_type in DISTRESS_TYPES
